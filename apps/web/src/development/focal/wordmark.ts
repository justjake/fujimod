/** The FujiMod pixel wordmark. Rows 0-10 run from cap height to the baseline;
 * rows 11-13 are the descender of the j. */
export const WORDMARK_ROWS = [
  '....#########.................##......##.............##',
  '...#....##....................##......##.............##',
  '..#.....##............##..##..###....###.............##',
  '.......##....................###....###.............##.',
  '.......##....................##.#..#.##.............##.',
  '....######..##..##...##..##..##.#..#.##....#####.#####.',
  '.......##...##..##..###..##..##..##..##...##..#.##..##.',
  '......##...##..##..###.###..##..##..##...##..#.##..##..',
  '.....#.....##..##.#.##.###..##......##...##..#.##..##..',
  '#....#.....##..##.#.###.##..##......##..###..#.##..##..',
  '.####.......###.##..##..###.##.......###..###...#######',
  '...................##..................................',
  '...............#...#...................................',
  '................###....................................',
];
export const WORDMARK_CAP_ROWS = 11;
export const WORDMARK_WIDTH = WORDMARK_ROWS[0].length;
export const WORDMARK_HEIGHT = WORDMARK_ROWS.length;

/** One SVG path: a rectangle per run of set pixels. */
export const WORDMARK_PATH = WORDMARK_ROWS.flatMap((row, y) =>
  [...row.matchAll(/#+/g)].map((run) => `M${run.index} ${y}h${run[0].length}v1h-${run[0].length}z`),
).join('');
