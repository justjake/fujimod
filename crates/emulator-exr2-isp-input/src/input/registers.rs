pub fn valid(o: usize, v: u32) -> bool {
    if mask(o).is_none_or(|m| v & !m != 0) {
        return false;
    }
    match o {
        8 | 12 | 0x30 if v & 3 == 3 => false,
        12 if v & 3 != 0 && v & 0x1010000 != 0 => false,
        0x10 if v >> 24 & 7 == 7 || v >> 16 & 7 == 7 || v >> 8 & 3 == 3 => false,
        0x24 => v <= 0x3000,
        0x170 | 0x270 | 0x354 | 0x370 => v >> 20 & 7 <= 4,
        0x398 => v >> 16 <= 0x2000,
        0x3ac => v & 7 <= 4,
        0x3b8 => v & 0xff000000 == 0xfb000000,
        0x50 | 0x78 => v >> 16 & 3 != 3 && v >> 1 & 3 != 3,
        0x38c => v & 0x10000 == 0 || v & 0x202 != 0,
        _ => true,
    }
}
